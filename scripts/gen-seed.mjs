// Bundles src/seed/** into src/seed-files.ts so the Worker can push the demo
// site into a fresh Artifacts trunk without any filesystem access at runtime.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = new URL("../src/seed", import.meta.url).pathname;
const files = {};
const walk = (dir) => {
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else files[relative(root, p)] = readFileSync(p, "utf8");
  }
};
walk(root);
const out = `// Generated by scripts/gen-seed.mjs from src/seed/**. Do not edit by hand.\nexport const SEED_FILES: Record<string, string> = ${JSON.stringify(files, null, 2)};\n`;
writeFileSync(new URL("../src/seed-files.ts", import.meta.url).pathname, out);
console.log(`wrote ${Object.keys(files).length} seed files`);
